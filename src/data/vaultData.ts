export const vaultFiles: VaultFile[] = rawVaultFiles.map((f) => ({
  ...f,
  downloadUrl: resolveDownloadUrl(f.relPath),
}));

// ─── Helpers ──────────────────────────────────────────────────────────────────
export function getVaultFiles(
  moduleId: string,
  type?: VaultFileType,
): VaultFile[] {
  return vaultFiles.filter(
    (f) => f.moduleId === moduleId && (type ? f.type === type : true),
  );
}

export function getModuleFileCount(moduleId: string): number {
  return vaultFiles.filter((f) => f.moduleId === moduleId).length;
}

export function getModuleProfessor(moduleId: string): string {
  return vaultFiles.find((f) => f.moduleId === moduleId)?.professor ?? 'Équipe Pédagogique';
}

export function getSemesterFileCount(semesterId: string): number {
  return vaultFiles.filter((f) => f.semesterId === semesterId).length;
}
