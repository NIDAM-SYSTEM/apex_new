// Vite glob import for all course and TD PDFs in src/assets/all_cours
const pdfModules = import.meta.glob('/src/assets/all_cours/**/*.{pdf,PDF}', {
  eager: true,
  query: '?url',
  import: 'default',
}) as Record<string, string>;

function resolveDownloadUrl(relPath: string): string {
  const fullKey = `/src/assets/all_cours/${relPath}`;
  if (pdfModules[fullKey]) {
    return pdfModules[fullKey];
  }
  // Case-insensitive lookup fallback
  const lowerTarget = fullKey.toLowerCase();
  for (const [k, v] of Object.entries(pdfModules)) {
    if (k.toLowerCase() === lowerTarget) {
      return v;
    }
  }
  return '#';
}

